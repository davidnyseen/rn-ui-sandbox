// Pregenerates a Google Cloud Text-to-Speech mp3 for every English line the app reads aloud — a reply() step's English
// prompt and each rule card ("Title. Body") — and writes src/generated/englishAudioMap.ts for src/tts.ts's speakEnglish().
// Same idea as generateThaiAudio.js: without it English fell back to the phone's own voice, which sounds noticeably
// worse next to the recorded Thai (user, 2026-11-08). Reads the lessons the app actually ships
// (src/generated/courseContent.json), so re-run it after re-exporting that file. Already-recorded lines are skipped.
//
// Usage: node scripts/generateEnglishAudio.js   (needs GOOGLE_CLOUD_TTS_API_KEY in .env)
'use strict';
const fs = require('fs');
const path = require('path');
const { hashStr } = require('./lib/courseBuilder');

const ROOT = path.join(__dirname, '..');
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio', 'english');
const MAP_PATH = path.join(ROOT, 'src', 'generated', 'englishAudioMap.ts');
const VOICE = 'en-US-Neural2-F';

function loadEnvKey(name) {
  const line = fs.readFileSync(path.join(ROOT, '.env'), 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`));
  if (!line) throw new Error(`${name} not found in .env — see .env.example`);
  return line.slice(name.length + 1).trim();
}

// The exact strings CourseLessonScreen passes to speakEnglish().
function collectEnglishStrings() {
  const { lessons } = require('../src/generated/courseContent.json');
  const set = new Set();
  for (const les of lessons) {
    const steps = Array.isArray(les.steps) ? les.steps : les.steps.steps || [];
    for (const step of steps) {
      if (step.type === 'reply' && step.english) set.add(step.english);
      if (step.type === 'rule') set.add(`${step.title}. ${step.body}`);
    }
  }
  return [...set];
}

async function synthesize(apiKey, text) {
  const res = await fetch(`https://texttospeech.googleapis.com/v1/text:synthesize?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      input: { text },
      voice: { languageCode: 'en-US', name: VOICE },
      audioConfig: { audioEncoding: 'MP3', speakingRate: 0.95 },
    }),
  });
  if (!res.ok) throw new Error(`synthesize failed for "${text.slice(0, 40)}": ${res.status} ${await res.text()}`);
  const { audioContent } = await res.json();
  return Buffer.from(audioContent, 'base64');
}

async function main() {
  const apiKey = loadEnvKey('GOOGLE_CLOUD_TTS_API_KEY');
  const strings = collectEnglishStrings();
  fs.mkdirSync(AUDIO_DIR, { recursive: true });
  let generated = 0;
  const entries = [];
  for (const text of strings) {
    const id = hashStr(text).toString(36);
    const file = path.join(AUDIO_DIR, `${id}.mp3`);
    entries.push({ text, id });
    if (fs.existsSync(file)) continue;
    fs.writeFileSync(file, await synthesize(apiKey, text));
    generated += 1;
  }
  const lines = [
    '// AUTO-GENERATED by scripts/generateEnglishAudio.js — do not edit by hand.',
    "// Literal English text -> bundled mp3 asset, consumed by src/tts.ts's speakEnglish().",
    'const englishAudioMap: Record<string, number> = {',
    ...entries.map(({ text, id }) => `  ${JSON.stringify(text)}: require(${JSON.stringify(`../../assets/audio/english/${id}.mp3`)}),`),
    '};',
    'export default englishAudioMap;',
    '',
  ];
  fs.writeFileSync(MAP_PATH, lines.join('\n'));
  console.log(`Done. ${generated} newly generated, ${entries.length} total mapped (voice ${VOICE}).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
