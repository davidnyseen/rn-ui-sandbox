// Emits supabase/seed_restaurant.sql from scripts/courseContent/restaurant.js —
// run with `node scripts/generateSeedSql.js`. Generating plain SQL (instead
// of pushing rows over the network with a service-role key) means seeding
// content never requires handling a sensitive key: the user runs the output
// file in the Supabase SQL Editor exactly the way supabase/schema.sql itself
// says to be run.
'use strict';
const fs = require('fs');
const path = require('path');
const { checkDictionary, stripAuthoringFields, addOrderDistractors, interleaveWordIntros } = require('./lib/courseBuilder');
const { restaurantSubject: raw } = require('./courseContent/restaurant');

checkDictionary(raw);
const interleaved = interleaveWordIntros(raw);
checkDictionary(interleaved);
const withDistractors = addOrderDistractors(interleaved);
checkDictionary(withDistractors);
const restaurantSubject = stripAuthoringFields(withDistractors);

// Dollar-quoting avoids ever having to escape single quotes/apostrophes —
// important here since English glosses like "I'd like..." contain them and
// the Thai/roman text is user-facing content we must reproduce exactly.
function sqlText(s) {
  return `$q$${s}$q$`;
}
function sqlJson(value) {
  return `$j$${JSON.stringify(value)}$j$::jsonb`;
}

const lines = [];
lines.push('-- Generated by scripts/generateSeedSql.js from scripts/courseContent/restaurant.js.');
lines.push('-- Run once in the Supabase SQL Editor, after supabase/schema.sql.');
lines.push('-- Regenerate + re-run any time the content file changes (upserts are idempotent).');
lines.push('');
lines.push('insert into public.course_subjects (id, title, roman, description, sort_order)');
lines.push('values');
lines.push(
  `  (${sqlText(restaurantSubject.id)}, ${sqlText(restaurantSubject.title)}, ${sqlText(restaurantSubject.roman)}, ${sqlText(restaurantSubject.description)}, 2)`
);
lines.push('on conflict (id) do update set');
lines.push('  title = excluded.title, roman = excluded.roman, description = excluded.description, sort_order = excluded.sort_order;');
lines.push('');
// A dialogue lesson's `steps` column holds the whole {kind, scene, lines,
// steps} payload (jsonb is schemaless) rather than a bare step array — see
// src/lib/courseContent.ts's row->CourseLesson mapping.
function lessonStepsJson(les) {
  return les.kind === 'dialogue' ? { kind: 'dialogue', scene: les.scene, lines: les.lines, steps: les.steps } : les.steps;
}

const currentLessonIds = restaurantSubject.lessons.map((les) => sqlText(les.id)).join(', ');
lines.push(`delete from public.course_lessons where subject_id = ${sqlText(restaurantSubject.id)} and id not in (${currentLessonIds});`);
lines.push('');
lines.push('insert into public.course_lessons (id, subject_id, sort_order, title, steps)');
lines.push('values');

const rows = restaurantSubject.lessons.map((les, i) => {
  return `  (${sqlText(les.id)}, ${sqlText(restaurantSubject.id)}, ${i}, ${sqlText(les.title)}, ${sqlJson(lessonStepsJson(les))})`;
});
lines.push(rows.join(',\n'));
lines.push('on conflict (id) do update set');
lines.push('  subject_id = excluded.subject_id, sort_order = excluded.sort_order, title = excluded.title, steps = excluded.steps;');
lines.push('');

const outPath = path.join(__dirname, '..', 'supabase', 'seed_restaurant.sql');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath}`);
