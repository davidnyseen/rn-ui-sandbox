// Emits supabase/seed_basics.sql from scripts/courseContent/basics.js —
// run with `node scripts/generateSeedSqlBasics.js`. See generateSeedSql.js
// for why this generates plain SQL instead of pushing rows with a key.
'use strict';
const fs = require('fs');
const path = require('path');
const { checkDictionary, stripAuthoringFields, addOrderDistractors, interleaveWordIntros, addUnitQuiz, checkQuizCoverage } = require('./lib/courseBuilder');
const { withOrderGroups } = require('./lib/orderGroups');
const { basicsSubject: raw } = require('./courseContent/basics');

checkDictionary(raw);
const interleaved = interleaveWordIntros(raw);
checkDictionary(interleaved);
const withDistractors = addOrderDistractors(interleaved);
checkDictionary(withDistractors);
const basicsSubject = withOrderGroups(checkQuizCoverage(addUnitQuiz(stripAuthoringFields(withDistractors))));

function sqlText(s) {
  return `$q$${s}$q$`;
}
function sqlJson(value) {
  return `$j$${JSON.stringify(value)}$j$::jsonb`;
}

const lines = [];
lines.push('-- Generated by scripts/generateSeedSqlBasics.js from scripts/courseContent/basics.js.');
lines.push('-- Run once in the Supabase SQL Editor, after supabase/schema.sql.');
lines.push('-- Regenerate + re-run any time the content file changes (upserts are idempotent).');
lines.push('');
lines.push('insert into public.course_subjects (id, title, roman, description, sort_order)');
lines.push('values');
lines.push(
  `  (${sqlText(basicsSubject.id)}, ${sqlText(basicsSubject.title)}, ${sqlText(basicsSubject.roman)}, ${sqlText(basicsSubject.description)}, 3)`
);
lines.push('on conflict (id) do update set');
lines.push('  title = excluded.title, roman = excluded.roman, description = excluded.description, sort_order = excluded.sort_order;');
lines.push('');
function lessonStepsJson(les) {
  return les.kind === 'dialogue' ? { kind: 'dialogue', scene: les.scene, lines: les.lines, steps: les.steps } : les.steps;
}

const currentLessonIds = basicsSubject.lessons.map((les) => sqlText(les.id)).join(', ');
lines.push(`delete from public.course_lessons where subject_id = ${sqlText(basicsSubject.id)} and id not in (${currentLessonIds});`);
lines.push('');
lines.push('insert into public.course_lessons (id, subject_id, sort_order, title, steps)');
lines.push('values');

const rows = basicsSubject.lessons.map((les, i) => {
  return `  (${sqlText(les.id)}, ${sqlText(basicsSubject.id)}, ${i}, ${sqlText(les.title)}, ${sqlJson(lessonStepsJson(les))})`;
});
lines.push(rows.join(',\n'));
lines.push('on conflict (id) do update set');
lines.push('  subject_id = excluded.subject_id, sort_order = excluded.sort_order, title = excluded.title, steps = excluded.steps;');
lines.push('');

const outPath = path.join(__dirname, '..', 'supabase', 'seed_basics.sql');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath}`);
