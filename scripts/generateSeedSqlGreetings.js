// Emits supabase/seed_greetings.sql from scripts/courseContent/greetings.js —
// run with `node scripts/generateSeedSqlGreetings.js`. See generateSeedSql.js
// for why this generates plain SQL instead of pushing rows with a key.
//
// greetings.js now exports two subjects (greetingsSubjects) instead of one —
// they used to be a single "Everyday Greetings & Small Talk" subject, split
// into smaller units. checkDictionary/interleaveWordIntros/
// addOrderDistractors take a shared `introduced` set/map threaded across
// both subjects in order, so the second subject's lessons can freely reuse
// vocabulary the first subject already taught.
'use strict';
const fs = require('fs');
const path = require('path');
const { checkDictionary, stripAuthoringFields, addOrderDistractors, interleaveWordIntros } = require('./lib/courseBuilder');
const { greetingsSubjects: rawSubjects } = require('./courseContent/greetings');

// `introduced` tracks only words taught by PRIOR subjects in the sequence —
// each subject is checked/interleaved against a copy of it (so its own
// words don't leak into its own ordering check), and only replaced with the
// post-subject result once that subject is fully validated, so the next
// subject starts from an accurate "everything taught so far" set.
let introduced = new Set();
const introducedTiles = new Map(); // thai -> roman, shared + mutated across subjects directly (order-safe: see addOrderDistractors)
const subjects = rawSubjects.map((raw) => {
  checkDictionary(raw, new Set(introduced)); // sanity-check the author's own lesson order
  const interleaved = interleaveWordIntros(raw, 2, new Set(introduced));
  introduced = checkDictionary(interleaved, new Set(introduced)); // real check; carries forward to the next subject
  const withDistractors = addOrderDistractors(interleaved, 2, introducedTiles);
  return stripAuthoringFields(withDistractors);
});

function sqlText(s) {
  return `$q$${s}$q$`;
}
function sqlJson(value) {
  return `$j$${JSON.stringify(value)}$j$::jsonb`;
}

const lines = [];
lines.push('-- Generated by scripts/generateSeedSqlGreetings.js from scripts/courseContent/greetings.js.');
lines.push('-- Run once in the Supabase SQL Editor, after supabase/schema.sql.');
lines.push('-- Regenerate + re-run any time the content file changes (upserts are idempotent).');
lines.push('');
lines.push("-- The old single 'greetings' subject was split into 'greetings-hello' and");
lines.push("-- 'greetings-names' — clean up the old subject id and its lessons.");
lines.push(`delete from public.course_lessons where subject_id = ${sqlText('greetings')};`);
lines.push(`delete from public.course_subjects where id = ${sqlText('greetings')};`);
lines.push('');

function lessonStepsJson(les) {
  return les.kind === 'dialogue' ? { kind: 'dialogue', scene: les.scene, lines: les.lines, steps: les.steps } : les.steps;
}

lines.push('insert into public.course_subjects (id, title, roman, description, sort_order)');
lines.push('values');
lines.push(
  subjects
    .map(
      (subj, i) =>
        `  (${sqlText(subj.id)}, ${sqlText(subj.title)}, ${sqlText(subj.roman)}, ${sqlText(subj.description)}, ${i})`
    )
    .join(',\n')
);
lines.push('on conflict (id) do update set');
lines.push('  title = excluded.title, roman = excluded.roman, description = excluded.description, sort_order = excluded.sort_order;');
lines.push('');

for (const subj of subjects) {
  const currentLessonIds = subj.lessons.map((les) => sqlText(les.id)).join(', ');
  lines.push(`delete from public.course_lessons where subject_id = ${sqlText(subj.id)} and id not in (${currentLessonIds});`);
}
lines.push('');
lines.push('insert into public.course_lessons (id, subject_id, sort_order, title, steps)');
lines.push('values');

const rows = subjects.flatMap((subj) =>
  subj.lessons.map((les, i) => `  (${sqlText(les.id)}, ${sqlText(subj.id)}, ${i}, ${sqlText(les.title)}, ${sqlJson(lessonStepsJson(les))})`)
);
lines.push(rows.join(',\n'));
lines.push('on conflict (id) do update set');
lines.push('  subject_id = excluded.subject_id, sort_order = excluded.sort_order, title = excluded.title, steps = excluded.steps;');
lines.push('');

const outPath = path.join(__dirname, '..', 'supabase', 'seed_greetings.sql');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${outPath}`);
