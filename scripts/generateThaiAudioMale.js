// Pregenerates a MALE-voiced Google Cloud TTS mp3 for every Thai line a
// reply() step (see scripts/lib/courseBuilder.js) has a male speaker say —
// context lines with speaker 'M', plus the tested reply itself when
// replySpeaker is 'M'. The bulk of the app's audio (src/generated/
// thaiAudioMap.ts, from generateThaiAudio.js) uses a single female Neural2
// voice; this is a small supplemental set so reply() chat steps can play a
// male voice for the male speaker's lines specifically, same
// bundled-not-live approach (see that script's header for why).
//
// Usage: node scripts/generateThaiAudioMale.js
// Requires GOOGLE_CLOUD_TTS_API_KEY in .env (see .env.example).
'use strict';
const fs = require('fs');
const path = require('path');
const { hashStr } = require('./lib/courseBuilder');

const ROOT = path.join(__dirname, '..');
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio', 'thai-male');
const MAP_PATH = path.join(ROOT, 'src', 'generated', 'thaiAudioMapMale.ts');
// No male Neural2 voice exists for th-TH (checked via voices.list) — this is
// Google's newer Chirp3-HD tier, generally a step up from Neural2 anyway.
const VOICE_NAME = 'th-TH-Chirp3-HD-Puck';

function loadEnvKey(name) {
  const envPath = path.join(ROOT, '.env');
  const text = fs.readFileSync(envPath, 'utf8');
  const line = text.split(/\r?\n/).find((l) => l.startsWith(`${name}=`));
  if (!line) throw new Error(`${name} not found in .env — see .env.example`);
  return line.slice(name.length + 1).trim();
}

function collectMaleLines() {
  const files = ['restaurant', 'greetings', 'basics', 'family', 'numbers', 'travel'];
  const set = new Set();
  for (const f of files) {
    const mod = require(`./courseContent/${f}`);
    // Most courseContent files export a single subject object; greetings.js
    // exports an array of subjects (greetingsSubjects, one per unit) —
    // normalize to an array either way so both shapes iterate the same.
    const val = Object.values(mod)[0];
    const subjects = Array.isArray(val) ? val : [val];
    for (const subj of subjects) {
    for (const les of subj.lessons) {
      if (les.kind === 'dialogue') continue;
      for (const step of les.steps) {
        if (step.type !== 'reply') continue;
        for (const line of step.context) {
          if (line.speaker === 'M') set.add(line.thai);
        }
        if (step.replySpeaker === 'M') set.add(step.thai);
      }
    }
    }
  }
  return [...set];
}

async function synthesize(apiKey, text) {
  const res = await fetch(`https://texttospeech.googleapis.com/v1/text:synthesize?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      input: { text },
      voice: { languageCode: 'th-TH', name: VOICE_NAME },
      audioConfig: { audioEncoding: 'MP3', speakingRate: 0.92 },
    }),
  });
  if (!res.ok) throw new Error(`synthesize failed for "${text}": ${res.status} ${await res.text()}`);
  const { audioContent } = await res.json();
  return Buffer.from(audioContent, 'base64');
}

async function main() {
  const apiKey = loadEnvKey('GOOGLE_CLOUD_TTS_API_KEY');
  const strings = collectMaleLines();
  console.log(`Found ${strings.length} unique male-speaker lines across all subjects.`);
  console.log(`Using voice: ${VOICE_NAME}`);

  fs.mkdirSync(AUDIO_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(MAP_PATH), { recursive: true });

  const entries = [];
  let generated = 0;
  let skipped = 0;
  for (const text of strings) {
    const id = hashStr(text).toString(36);
    const filePath = path.join(AUDIO_DIR, `${id}.mp3`);
    entries.push({ text, id });
    if (fs.existsSync(filePath)) {
      skipped += 1;
      continue;
    }
    const audio = await synthesize(apiKey, text);
    fs.writeFileSync(filePath, audio);
    generated += 1;
  }

  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generateThaiAudioMale.js — do not edit by hand.');
  lines.push("// Literal Thai text -> bundled mp3 asset (male voice), consumed by src/tts.ts's speakThai().");
  lines.push('const thaiAudioMapMale: Record<string, number> = {');
  for (const { text, id } of entries) {
    lines.push(`  ${JSON.stringify(text)}: require(${JSON.stringify(`../../assets/audio/thai-male/${id}.mp3`)}),`);
  }
  lines.push('};');
  lines.push('export default thaiAudioMapMale;');
  lines.push('');
  fs.writeFileSync(MAP_PATH, lines.join('\n'));

  console.log(`Done. ${generated} newly generated, ${skipped} already cached, ${entries.length} total mapped.`);
  console.log(`Wrote ${MAP_PATH}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
